class _Response:
    status_code = 200
    ok = True
    text = ""

    def __init__(self, payload: dict):
        self._payload = payload

    def json(self) -> dict:
        return self._payload


class _Session:
    def __init__(self):
        self.headers: dict[str, str] = {}
        self.calls: list[dict] = []

    def post(self, url: str, **kwargs):
        self.calls.append({"url": url, **kwargs})
        return _Response({"id": 41})


class _HandlerClient:
    def __init__(self):
        self.text_calls: list[tuple[str, dict]] = []
        self.url_calls: list[dict] = []
        self.generated: list[int] = []
        self.file_calls: list[tuple[list[tuple[str, bytes, str]], dict]] = []
        self.bulk_calls: list[list[dict]] = []

    def get_me(self) -> dict:
        return {"id": 99, "plan": "pro"}

    def create_project_from_text(self, content_text: str, **fields) -> dict:
        self.text_calls.append((content_text, fields))
        return {
            "id": 73,
            "blog_url": "upload://documents",
            "template": fields.get("template", "default"),
            "voice_gender": fields.get("voice_gender", "female"),
            "voice_accent": fields.get("voice_accent", "american"),
            "aspect_ratio": fields.get("aspect_ratio", "landscape"),
            "video_length": fields.get("video_length", "auto"),
            "stock_footage_enabled": fields.get("stock_footage_enabled", False),
            "status": "created",
        }

    def create_project(self, **fields) -> dict:
        self.url_calls.append(fields)
        return {"id": 74, "blog_url": fields["blog_url"], "status": "created"}

    def create_project_from_files(self, files, **fields) -> dict:
        self.file_calls.append((files, fields))
        return {"id": 75, "blog_url": "upload://documents", "status": "created"}

    def create_projects_bulk(self, projects: list[dict]) -> dict:
        self.bulk_calls.append(projects)
        return {"project_ids": [81, 82]}

    def start_generation(self, project_id: int) -> dict:
        self.generated.append(project_id)
        return {"started": True}


def _tool(name: str):
    return next(tool for tool in get_tool_definitions() if tool.name == name)


def test_start_video_schema_accepts_source_or_bare_create_request():
    tool = _tool("start_video")
    schema = tool.inputSchema

    assert "blog_url" in schema["properties"]
    assert "content_text" in schema["properties"]
    assert "source_mode" in schema["properties"]
    assert "oneOf" not in schema
    assert tool.meta["openai/outputTemplate"] == handlers.SETUP_RESOURCE_URI


