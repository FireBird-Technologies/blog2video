def test_file_and_bulk_handlers_create_projects(monkeypatch):
    client = _HandlerClient()
    monkeypatch.setattr(
        handlers,
        "_download_widget_files",
        lambda files: [("article.pdf", b"pdf", "application/pdf")],
    )

    file_result = handlers._create_project_from_files(
        {"files": [{"file_id": "file-1", "download_url": "https://files.example/a"}], "template": "starlit"},
        client,
    )
    bulk_result = handlers._create_projects_bulk(
        {"projects": [
            {
                "blog_url": "https://example.com/one",
                "template": "starlit",
                "voice_gender": "none",
                "content_language": "es",
            },
            {"blog_url": "https://example.com/two", "template": "starlit"},
        ]},
        client,
    )

    assert client.file_calls[0][0][0][0] == "article.pdf"
    assert client.file_calls[0][1]["template"] == "starlit"
    assert "project #75" in file_result[0].text
    assert client.bulk_calls[0][1]["blog_url"] == "https://example.com/two"
    assert client.bulk_calls[0][0]["voice_gender"] == "none"
    assert client.bulk_calls[0][0]["content_language"] == "es"
    assert "project_ids: 81, 82" in bulk_result[0].text


