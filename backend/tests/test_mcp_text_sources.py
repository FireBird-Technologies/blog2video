def test_client_sends_pasted_text_through_web_app_upload_endpoint():
    client = Blog2VideoClient(jwt_token="token", base_url="https://api.example")
    session = _Session()
    client.session = session

    result = client.create_project_from_text(
        "Full article body",
        name="My article",
        template="nightfall",
        stock_footage_enabled=True,
    )

    assert result == {"id": 41}
    call = session.calls[0]
    assert call["url"] == "https://api.example/api/projects/upload"
    assert call["data"] == {
        "name": "My article",
        "template": "nightfall",
        "stock_footage_enabled": True,
    }
    filename, body, content_type = call["files"]["files"]
    assert filename == "pasted-content.txt"
    assert body == b"Full article body"
    assert content_type == "text/plain"


