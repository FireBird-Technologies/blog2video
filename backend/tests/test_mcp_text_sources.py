def test_upload_endpoint_keeps_mcp_media_settings(
    client,
    db_session,
    free_user,
    auth,
    monkeypatch,
):
    monkeypatch.setattr(
        projects_router,
        "extract_from_documents",
        lambda project, files, db: project,
    )

    response = client.post(
        "/api/projects/upload",
        headers=auth(free_user),
        files={"files": ("pasted-content.txt", b"Article body", "text/plain")},
        data={
            "playback_speed": "1.25",
            "captions_enabled": "true",
            "caption_position": "top_center",
            "caption_font_family": "oswald",
            "caption_font_size": "42",
            "caption_offset": "12",
        },
    )

    assert response.status_code == 200, response.text
    project = db_session.query(Project).filter(Project.id == response.json()["id"]).one()
    assert project.blog_url == "upload://documents"
    assert project.playback_speed == 1.25
    assert project.captions_enabled is True
    assert project.caption_position == "top_center"
    assert project.caption_font_family == "oswald"
    assert project.caption_font_size == "42"
    assert project.caption_offset == 12
