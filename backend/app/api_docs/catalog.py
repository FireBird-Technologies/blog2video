def _p(name, loc, typ, required, desc):
    return {"name": name, "in": loc, "type": typ, "required": required, "description": desc}


def _f(name, typ, required, desc):
    return {"name": name, "type": typ, "required": required, "description": desc}


def ep(
    method: str,
    path: str,
    summary: str,
    description: str = "",
    *,
    params: list[tuple] | None = None,
    body: list[tuple] | None = None,
    content_type: str = JSON,
    request: Any = None,
    response: Any = None,
    status: int = 200,
    response_note: str | None = None,
    errors: list[str] | None = None,
) -> dict:
    return {
        "method": method,
        "path": path,
        "summary": summary,
        "description": description,
        "params": [_p(*p) for p in (params or [])],
        "body": {"content_type": content_type, "fields": [_f(*f) for f in body]} if body else None,
        "request_example": request,
        "status": status,
        "response_example": response,
        "response_note": response_note,
        "errors": errors or [],
    }


