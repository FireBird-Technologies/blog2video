"""Hand-written public API reference, served to paid users by GET /api/api-docs.

Covers every route an API key may call (services/api_route_policy.py) plus the
simplified /api/v1 endpoints. tests/test_api_docs.py fails if an allowed route
has no entry here or an entry names a route that doesn't exist, so edit this
file whenever the policy changes.

Paths are written relative to the host (``/api/...``); the docs page prefixes
the deployment's base URL.
"""
from __future__ import annotations

from typing import Any

JSON = "application/json"
MULTIPART = "multipart/form-data"
